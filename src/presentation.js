const valid = id => typeof id === 'string' && Object.hasOwn(BOND_MAP, id);
export function bondSummary(id) {
  if(!valid(id))return '暂无羁绊说明';
  const text=id.startsWith('S')?BOND_MAP[id].description:SUMMARIES[id]||BOND_MAP[id].description;
  return text.replace(/。(?!$)/g,'。\n');
}
export function bondGrowth(id) {
  return valid(id) && GROWTH[id] ? GROWTH[id].map((description, index) => ({ progress: [2, 5, 9][index], description })) : [];
}
export function bondTags(id) {
  if (!valid(id)) return [];
  return [BOND_MAP[id].grade === 'evolution' ? '成长' : BOND_MAP[id].grade === 'core' ? '核心机制' : '属性强化'];
}
